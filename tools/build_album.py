"""Build the year slideshows: every photo in incoming/, grouped by the year it was taken.

Usage (from the repo root): python3 tools/build_album.py
Writes public/photos/album/<year>/<n>.webp and fills each
<!-- slides:YEAR:start --> ... <!-- slides:YEAR:end --> block in public/index.html
(full-screen background slides) and <!-- cards:YEAR --> blocks (extra carousel cards).
incoming/featured.txt ("<year> <file name>") picks the first slide of a year;
photos already used in the wedding cards are skipped for the cards block.
A photo inside incoming/<year>/ always belongs to that year.
incoming/goals/<year>/ holds the picture for each "next five" tile. Photos without a saved date use the year given in
incoming/years.txt ("<file name> <year>" per line), or else join the last year.
"""
import html
import re
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

from PIL import Image, ImageOps

try:  # iPhone HEIC photos
    from pillow_heif import register_heif_opener
    register_heif_opener()
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "incoming"
OUT = ROOT / "public" / "photos" / "album"
PAGE = ROOT / "public" / "index.html"
EXTS = {".jpg", ".jpeg", ".png", ".heic", ".webp", ".tif", ".tiff"}


def taken(im: Image.Image):
    exif = im.getexif()
    raw = exif.get_ifd(0x8769).get(36867) or exif.get(306)
    try:
        return datetime.strptime(str(raw), "%Y:%m:%d %H:%M:%S")
    except ValueError:
        return None


def save(im: Image.Image, dst: Path, size: int) -> None:
    im = im.copy()
    im.thumbnail((size, size), Image.LANCZOS)
    im.save(dst, "WEBP", quality=78, method=6)  # no exif=, so no location data


def main() -> int:
    photos = []
    for p in sorted(SRC.rglob("*")):
        if p.suffix.lower() not in EXTS or "goals" in p.parts:
            continue
        with Image.open(p) as im:
            when = taken(im)
            img = ImageOps.exif_transpose(im).convert("RGB")
        photos.append((when, p, img))
    photos.sort(key=lambda x: (x[0] is None, x[0] or datetime.max, x[1].name))

    years = {}
    listed = SRC / "years.txt"
    if listed.exists():
        for line in listed.read_text().splitlines():
            parts = line.split()
            if len(parts) == 2 and not line.startswith("#"):
                years[parts[0]] = int(parts[1])

    featured = {}
    listed = SRC / "featured.txt"
    if listed.exists():
        for line in listed.read_text().splitlines():
            parts = line.split()
            if len(parts) == 2 and not line.startswith("#"):
                featured[int(parts[0])] = parts[1]

    groups = defaultdict(list)
    for when, p, img in photos:
        if p.parent.name.isdigit():  # a photo put in incoming/<year>/ belongs to that year
            groups[int(p.parent.name)].append((when, p, img))
        elif when:
            groups[when.year].append((when, p, img))
        elif p.name in years:
            groups[years[p.name]].append((None, p, img))
    last = max(groups) if groups else None
    for when, p, img in photos:
        if not when and not p.parent.name.isdigit() and p.name not in years and last:
            groups[last].append((None, p, img))
    for year, items in groups.items():
        items.sort(key=lambda x: x[1].name != featured.get(year))  # featured first, rest keep date order

    page = PAGE.read_text()

    used = set(re.findall(r"<!-- from (\S+) -->", page))
    for year, items in sorted(groups.items()):
        folder = OUT / str(year)
        folder.mkdir(parents=True, exist_ok=True)
        slides, cards = [], []
        for n, (when, p, img) in enumerate(items, 1):
            save(img, folder / f"{n:02d}.webp", 2000)
            rel = f"photos/album/{year}/{n:02d}.webp"
            alt = f"Photo from {when:%-d %b %Y}" if when else f"Photo from {year}"
            lazy = "" if n == 1 else ' loading="lazy"'
            slides.append(f'<div class="slide"><img src="{rel}" alt="{alt}"{lazy}></div>')
            if p.name not in used:
                cards.append(f'<div class="card"><div class="scene"><img src="{rel}" alt="{alt}" loading="lazy"></div></div>')
        for kind, parts in (("slides", slides), ("cards", cards)):
            block = (f"<!-- {kind}:{year}:start (generated by tools/build_album.py) -->\n    "
                     + "\n    ".join(parts) + f"\n    <!-- {kind}:{year}:end -->")
            page, count = re.subn(rf"<!-- {kind}:{year}:start.*?<!-- {kind}:{year}:end -->", lambda _: block, page, flags=re.S)
            if count:
                print(f"{year} {kind}: {len(parts)} photos")
    PAGE.write_text(page)

    # "The next five": the first photo in incoming/goals/<year>/ becomes that year's tile
    for folder in sorted((SRC / "goals").glob("*")):
        pics = sorted(p for p in folder.glob("*") if p.suffix.lower() in EXTS)
        if pics:
            with Image.open(pics[0]) as im:
                save(ImageOps.exif_transpose(im).convert("RGB"), ROOT / "public" / "photos" / "goals" / f"{folder.name}.webp", 2000)
            print(f"goal {folder.name}: {pics[0].name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

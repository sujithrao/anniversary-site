"""Build the photo album: every photo in incoming/, grouped by the year it was taken.

Usage (from the repo root): python3 tools/build_album.py
Writes public/photos/album/<year>/<n>.webp (thumbnail) and <n>-full.webp,
and rewrites the album between the album markers in public/index.html.
Photos without a saved date go under "More".
"""
import html
import re
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

from PIL import Image, ImageOps

try:  # iPhone HEIC photos
    from pillow_heif import register_heif_opener
    register_heif_opener()
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "incoming"
OUT = ROOT / "public" / "photos" / "album"
PAGE = ROOT / "public" / "index.html"
EXTS = {".jpg", ".jpeg", ".png", ".heic", ".webp", ".tif", ".tiff"}


def taken(im: Image.Image):
    exif = im.getexif()
    raw = exif.get_ifd(0x8769).get(36867) or exif.get(306)
    try:
        return datetime.strptime(str(raw), "%Y:%m:%d %H:%M:%S")
    except ValueError:
        return None


def save(im: Image.Image, dst: Path, size: int) -> None:
    im = im.copy()
    im.thumbnail((size, size), Image.LANCZOS)
    im.save(dst, "WEBP", quality=78, method=6)  # no exif=, so no location data


def main() -> int:
    photos = []
    for p in sorted(SRC.rglob("*")):
        if p.suffix.lower() not in EXTS:
            continue
        with Image.open(p) as im:
            when = taken(im)
            img = ImageOps.exif_transpose(im).convert("RGB")
        photos.append((when, p, img))
    photos.sort(key=lambda x: (x[0] is None, x[0] or datetime.max, x[1].name))

    groups = defaultdict(list)
    for when, p, img in photos:
        groups[str(when.year) if when else "More"].append((when, img))

    tabs, panes = [], []
    for i, (key, items) in enumerate(groups.items()):
        folder = OUT / key.lower()
        folder.mkdir(parents=True, exist_ok=True)
        figs = []
        for n, (when, img) in enumerate(items, 1):
            save(img, folder / f"{n:02d}.webp", 700)
            save(img, folder / f"{n:02d}-full.webp", 1800)
            rel = f"photos/album/{key.lower()}/{n:02d}"
            label = when.strftime("%-d %b %Y") if when else ""
            figs.append(
                f'<button type="button" class="ph-btn" data-full="{rel}-full.webp" data-cap="{html.escape(label)}">'
                f'<img src="{rel}.webp" alt="Photo{(" from " + label) if label else ""}" loading="lazy"></button>'
            )
        on = "true" if i == 0 else "false"
        tabs.append(f'<button type="button" role="tab" id="tab-{key}" aria-controls="pane-{key}" aria-selected="{on}">{key}<small>{len(items)}</small></button>')
        hidden = "" if i == 0 else " hidden"
        panes.append(f'<div class="grid" role="tabpanel" id="pane-{key}" aria-labelledby="tab-{key}"{hidden}>\n      ' + "\n      ".join(figs) + "\n    </div>")
        print(f"{key}: {len(items)} photos")

    block = (
        '<!-- album:start (generated by tools/build_album.py) -->\n'
        '    <div class="tabs" role="tablist" aria-label="Years">' + "".join(tabs) + "</div>\n    "
        + "\n    ".join(panes)
        + "\n    <!-- album:end -->"
    )
    page = PAGE.read_text()
    page, count = re.subn(r"<!-- album:start.*?<!-- album:end -->", lambda _: block, page, flags=re.S)
    if count != 1:
        print("album markers not found in index.html", file=sys.stderr)
        return 1
    PAGE.write_text(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())

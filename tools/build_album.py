"""Build the per-year photo strips: every photo in incoming/, grouped by the year it was taken.

Usage (from the repo root): python3 tools/build_album.py
Writes public/photos/album/<year>/<n>.webp (thumbnail) and <n>-full.webp,
and fills each <!-- strip:YEAR:start --> ... <!-- strip:YEAR:end --> block in
public/index.html. Photos without a saved date are added to the last year.
"""
import html
import re
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

from PIL import Image, ImageOps

try:  # iPhone HEIC photos
    from pillow_heif import register_heif_opener
    register_heif_opener()
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "incoming"
OUT = ROOT / "public" / "photos" / "album"
PAGE = ROOT / "public" / "index.html"
EXTS = {".jpg", ".jpeg", ".png", ".heic", ".webp", ".tif", ".tiff"}


def taken(im: Image.Image):
    exif = im.getexif()
    raw = exif.get_ifd(0x8769).get(36867) or exif.get(306)
    try:
        return datetime.strptime(str(raw), "%Y:%m:%d %H:%M:%S")
    except ValueError:
        return None


def save(im: Image.Image, dst: Path, size: int) -> None:
    im = im.copy()
    im.thumbnail((size, size), Image.LANCZOS)
    im.save(dst, "WEBP", quality=78, method=6)  # no exif=, so no location data


def main() -> int:
    photos = []
    for p in sorted(SRC.rglob("*")):
        if p.suffix.lower() not in EXTS:
            continue
        with Image.open(p) as im:
            when = taken(im)
            img = ImageOps.exif_transpose(im).convert("RGB")
        photos.append((when, p, img))
    photos.sort(key=lambda x: (x[0] is None, x[0] or datetime.max, x[1].name))

    groups = defaultdict(list)
    for when, p, img in photos:
        if when:
            groups[when.year].append((when, img))
    last = max(groups) if groups else None
    for when, p, img in photos:
        if not when and last:
            groups[last].append((None, img))

    page = PAGE.read_text()
    for year, items in sorted(groups.items()):
        folder = OUT / str(year)
        folder.mkdir(parents=True, exist_ok=True)
        thumbs = []
        for n, (when, img) in enumerate(items, 1):
            save(img, folder / f"{n:02d}.webp", 360)
            save(img, folder / f"{n:02d}-full.webp", 1800)
            rel = f"photos/album/{year}/{n:02d}"
            label = when.strftime("%-d %b %Y") if when else ""
            thumbs.append(
                f'<button type="button" class="ph-btn" data-full="{rel}-full.webp" data-cap="{html.escape(label)}">'
                f'<img src="{rel}.webp" alt="Photo{(" from " + label) if label else ""}" loading="lazy"></button>'
            )
        block = (
            f"<!-- strip:{year}:start (generated by tools/build_album.py) -->\n"
            f'    <div class="strip" aria-label="{len(items)} photos from {year}">' + "".join(thumbs) + "</div>\n"
            f"    <!-- strip:{year}:end -->"
        )
        page, count = re.subn(rf"<!-- strip:{year}:start.*?<!-- strip:{year}:end -->", lambda _: block, page, flags=re.S)
        print(f"{year}: {len(items)} photos" + ("" if count else " (no strip in index.html, skipped)"))
    PAGE.write_text(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
